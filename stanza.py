def to_cyrillic(text):
    mapping = {'q': 'қ', 'ǵ': 'ғ', 'ń': 'ң', 'sh': 'ш', 'ch': 'ч', 'ı': 'і',
               'ó': 'ө', 'ú': 'ү', 'w': 'ў', 'a': 'а', 'b': 'б', 'd': 'д',
               'e': 'е', 'f': 'ф', 'g': 'г', 'h': 'һ', 'i': 'и', 'j': 'ж',
               'k': 'к', 'l': 'л', 'm': 'м', 'n': 'н', 'o': 'о', 'p': 'п',
               'r': 'р', 's': 'с', 't': 'т', 'u': 'у', 'v': 'в', 'y': 'й', 'z': 'з'}
    pattern = re.compile('|'.join(re.escape(k) for k in sorted(mapping.keys(), key=len, reverse=True)))
    return pattern.sub(lambda m: mapping[m.group(0)], text.lower())


