def filter_karakalpak_pos(raw_tokens):
    """Applies specific Karakalpak grammar rules over Stanza's Turkish output."""
    merged_tokens = []
    skip_next = False


    for i in range(len(raw_tokens)):
        if skip_next:
            skip_next = False
            continue

        current = raw_tokens[i]

        if i + 1 < len(raw_tokens):
            next_t = raw_tokens[i + 1]

            if (
                next_t["token"] in ["ń", "ǵı", "te", "ti", "tı", "ni", "nı"]
                and current["sent_id"] == next_t["sent_id"]
            ):
                current["token"] = f"{current['token']}'{next_t['token']}"
                if current["pos"] in ["NUM", "VERB"]:
                    current["pos"] = "NOUN"
                skip_next = True

        merged_tokens.append(current)


    HARD_MAPPINGS = {
        "ushın": "ADP",
        "menen": "ADP",
        "hám": "CCONJ",
        "ol": "PRON",
        "olar": "PRON",
        "emes": "AUX",
        "edi": "AUX",
        "boldı": "VERB",
        "kerek": "ADJ",
    }

    for item in merged_tokens:
        token_lower = item["token"].lower()

        # Rule 1: Static dictionary overrides
        if token_lower in HARD_MAPPINGS:
            item["pos"] = HARD_MAPPINGS[token_lower]
            continue

        # Rule 2: Verbal nouns (gerunds) ending in -iw / -ıw plus case variations
        if re.search(r"[iı]w(ǵa|ge|dı|di|dan|den|lar)?$", token_lower):
            item["pos"] = "VERB"
            continue

        # Rule 3: Karakalpak Participles ending in -atuǵın, -etuǵın, -tuǵın
        if re.search(r"[ae]?tuǵın$", token_lower):
            item["pos"] = "VERB"
            continue

        # Rule 4: Past / continuous markers ending in -ǵan, -gen, -qan, -ken, -atır
        if re.search(r"(ǵan|gen|qan|ken|atır)$", token_lower) and item[
            "pos"
        ] in ["NUM", "NOUN"]:
            item["pos"] = "VERB"
            continue

    return merged_tokens



